def bench_enc():
    res = {"levels": [], "edges": [], "glitch": [], "turn": []}
    decks = []
    # glitch run: close-glitches while open (2..16 ms), clean close at 20 ms,
    # open-glitches while closed (22..36 ms), clean open at 40 ms.
    ev = []
    for k, w in enumerate(ENC_W):
        t = 2e-3 + 2e-3 * k
        ev += [(t, 1), (t + w, 0)]
    ev.append((20e-3, 1))
    for k, w in enumerate(ENC_W):
        t = 22e-3 + 2e-3 * k
        ev += [(t, 0), (t + w, 1)]
    ev.append((40e-3, 0))
    glitch_pwl = pwl_from_events(ev, 43e-3)
    for rpu in (50e3, 80e3, 0):
        n = tag("enc_glitch", rpu)
        decks.append((n, enc_body(glitch_pwl, rpu), "tran 1u 43m 0 1u\nwrdata %s.dat v(enc)" % n))
    # fast turn: A/B Gray sequence, one contact edge every 1 ms (EC11 15 pulses/rev:
    # 60 edges/rev -> 16.7 rev/s), every edge with 200 us of bounce (3 extra changes).
    def bounce(t, lv):
        b = [(t, lv), (t + 40e-6, 1 - lv), (t + 70e-6, lv), (t + 150e-6, 1 - lv), (t + 200e-6, lv)]
        return b
    seq_a, seq_b = [], []
    a = b = 0
    gray = [(0, 0), (1, 0), (1, 1), (0, 1)]  # (A closed, B closed)
    steps = 24
    for k in range(1, steps + 1):
        na, nb = gray[k % 4]
        t = 1e-3 * k
        if na != a:
            seq_a += bounce(t, na)
        if nb != b:
            seq_b += bounce(t, nb)
        a, b = na, nb
    t_end = 1e-3 * (steps + 2)
    for ch, seq in (("a", seq_a), ("b", seq_b)):
        n = tag("enc_turn", ch)
        decks.append((n, enc_body(pwl_from_events(seq, t_end), 50e3),
                      "tran 1u %g 0 1u\nwrdata %s.dat v(enc)" % (t_end, n)))
    run_all(decks)

    for rpu in (50e3, 80e3, 0):
        n = tag("enc_glitch", rpu)
        d = read_dat(n + ".dat")
        t, v = d["time"], d["v(enc)"]
        res["levels"].append({"rpu": rpu, "v_low_V": round(interp(t, v, 39.9e-3), 3),
                              "v_high_V": round(interp(t, v, 1.9e-3), 3)})
        for sname, (vtp, vtm) in SCHMITT.items():
            sw = schmitt(t, v, vtp, vtm, 1)
            fall = [s for s in sw if 20e-3 <= s[0] < 21.9e-3 and s[1] == 0]
            rise = [s for s in sw if 40e-3 <= s[0] < 43e-3 and s[1] == 1]
            res["edges"].append({"rpu": rpu, "schmitt": sname,
                                 "close_to_low_us": us(fall[0][0] - 20e-3) if fall else None,
                                 "open_to_high_us": us(rise[0][0] - 40e-3) if rise else None})
            row = {"rpu": rpu, "schmitt": sname, "close_glitch_passes_us": [], "open_glitch_passes_us": []}
            for k, w in enumerate(ENC_W):
                t0 = 2e-3 + 2e-3 * k
                if any(t0 <= s[0] < t0 + 1.9e-3 for s in sw):
                    row["close_glitch_passes_us"].append(round(w * 1e6))
                t0 = 22e-3 + 2e-3 * k
                if any(t0 <= s[0] < t0 + 1.9e-3 for s in sw):
                    row["open_glitch_passes_us"].append(round(w * 1e6))
            res["glitch"].append(row)
    da = read_dat(tag("enc_turn", "a") + ".dat")
    db = read_dat(tag("enc_turn", "b") + ".dat")
    t, va, vb = da["time"], da["v(enc)"], db["v(enc)"]
    for sname, (vtp, vtm) in SCHMITT.items():
        for poll in (0, 100e-6, 250e-6):
            sa = schmitt(t, va, vtp, vtm, 1)
            sb = schmitt(t, vb, vtp, vtm, 1)

            def level(sw, tt):
                lv = 1
                for ts, l in sw:
                    if ts > tt:
                        break
                    lv = l
                return lv
            times = sorted({s[0] for s in sa + sb}) if poll == 0 else \
                [k * poll for k in range(int(t[-1] / poll))]
            prev = (level(sa, 0) << 1) | level(sb, 0)
            count = invalid = 0
            for tt in times:
                cur = (level(sa, tt + 1e-9) << 1) | level(sb, tt + 1e-9)
                if cur != prev:
                    dlt = QUAD[(prev << 2) | cur]
                    count += dlt
                    if dlt == 0:
                        invalid += 1
                prev = cur
            res["turn"].append({"schmitt": sname, "poll_us": round(poll * 1e6), "count": count,
                                "expected": steps, "skipped_states": invalid})
    return res


