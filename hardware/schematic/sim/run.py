    decks = []
    cases = [(5.0, rl, cl, 40) for rl in (100e3, 10e3) for cl in (0, 1e-9, 10e-9)]
    cases += [(4.5, 10e3, cl, 70) for cl in (0, 10e-9)]
    cases += [(5.0, 0.01, 0, 40)]
    for vb, rl, cl, rout in cases:
        n = tag("gate", vb, rl, cl, rout)
        body = "\n".join([
            "Vbus vbus 0 %g" % vb,
            "Vgpio gpio 0 PWL(0 0 5u 0 5.002u 3.3 205u 3.3 205.002u 0 405u 0)",
            "R531 gpio 0 100k",
            "Xu504 gpio buf vbus 0 CMOSBUF params: VTH=1.5 TE=3n ROUT=%g" % rout,
            "R541 buf jack 1k",
            "Rload jack 0 %g" % rl,
        ] + (["Ccable jack 0 %g" % cl] if cl else []))
        ctl = "tran 1n 405u 0 5n\nlet igate = (v(buf)-v(jack))/1k\nwrdata %s.dat v(jack) v(buf) igate" % n
        decks.append((n, body, ctl))
    run_all(decks)
    for vb, rl, cl, rout in cases:
        n = tag("gate", vb, rl, cl, rout)
        d = read_dat(n + ".dat")
        t, j, i = d["time"], d["v(jack)"], d["igate"]
        vh = interp(t, j, 200e-6)
        vl = interp(t, j, 400e-6)
        r = {"vbus": vb, "rl": rl, "cl": cl, "rout": rout, "v_high_V": round(vh, 3), "v_low_mV": mv(vl),
             "i_high_mA": round(interp(t, i, 200e-6) * 1e3, 2)}
        if rl > 1:
            r["t_rise_10_90_us"] = us(edge_10_90(t, j, 0, vh, True, 5e-6, 200e-6))
            r["t_fall_90_10_us"] = us(edge_10_90(t, j, 0, vh, False, 205e-6, 400e-6))
            c25 = crossings(t, j, 2.5, True, 5e-6, 200e-6)
            r["t_to_2V5_us"] = us(c25[0] - 5e-6) if c25 else None
            c10 = crossings(t, j, 1.0, False, 205e-6, 400e-6)
            r["t_below_1V_us"] = us(c10[0] - 205e-6) if c10 else None
        res.append(r)
    return res


