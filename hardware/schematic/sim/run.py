VENDOR_INCLUDE = "mcp6001_ngspice.lib"
# Rev F (MCP6001_MM_F.zip, 2012) has unbalanced parentheses in the two output-clamp
# tables; PSpice reads them as below. Everything else is used as published, with
# ngspice's PSpice compatibility (set ngbehavior=ps).
VENDOR_FIXES = [
    ("G35 33 0 TABLE {V(35,3)} ((-1,-1n)(0,0)(16,1n))(16.1,1))",
     "G35 33 0 TABLE {V(35,3)} ((-1,-1n)(0,0)(16,1n)(16.1,1))"),
    ("G36 33 0 TABLE {V(35,4)} ((-16.1,-1)((-16,-1n)(0,0)(1,1n))",
     "G36 33 0 TABLE {V(35,4)} ((-16.1,-1)(-16,-1n)(0,0)(1,1n))"),
]


def vendor_setup():
    d = os.path.join(OUT, "vendor")
    os.makedirs(d, exist_ok=True)
    src = open(MCP6001_LIB, newline="").read().replace("\r\n", "\n")
    if ".SUBCKT MCP6001 1 2 3 4 5" not in src:
        raise SystemExit("MCP6001_LIB: %s is not Microchip's MCP6001 macro-model" % MCP6001_LIB)
    with open(os.path.join(d, "mcp6001_asis.lib"), "w") as f:
        f.write(src.replace(".SUBCKT MCP6001 ", ".SUBCKT MCP6001ASIS ").replace(".ENDS MCP6001", ".ENDS MCP6001ASIS"))
    for a, b in VENDOR_FIXES:
        src = src.replace(a, b)
    with open(os.path.join(d, VENDOR_INCLUDE), "w") as f:
        f.write(src)
    with open(os.path.join(d, ".spiceinit"), "w") as f:
        f.write("set ngbehavior=ps\n")


