BIT = 32e-6  # 31250 baud


def uart_pwl(byte, v, t0=20e-6, edge=5e-9, idle_after=60e-6):
    bits = [0] + [(byte >> k) & 1 for k in range(8)] + [1]
    pts = [(0, v)]
    level = 1
    t = t0
    for b in bits:
        if b != level:
            pts += [(t, level * v), (t + edge, b * v)]
            level = b
        t += BIT
    pts.append((t + idle_after, level * v))
    return " ".join("%.7g %.4g" % p for p in pts), t + idle_after


def cable(n_sections, a4, a5, b4, b5):
    if n_sections == 0:
        return "R0c4 %s %s 1m\nR0c5 %s %s 1m" % (a4, b4, a5, b5)
    lines = []
    nodes4 = [a4] + ["c4_%d" % k for k in range(1, n_sections)] + [b4]
    nodes5 = [a5] + ["c5_%d" % k for k in range(1, n_sections)] + [b5]
    for k in range(n_sections):
        lines.append("Xcab%d %s %s %s %s MIDICAB5M" % (k, nodes4[k], nodes5[k], nodes4[k + 1], nodes5[k + 1]))
    return "\n".join(lines)


def midi_tx_ours(v33, r403=33, r402=10, rol=20):
    """sheet midi: GPIO 0 (R401 10 k pull-up) -> U401 74LVC1G14 inverter -> R406 470 -> Q401 MMBT3904
    base (R407 10 k to GND); collector -> R402 10R -> FB401 -> J401 pin 5; +3V3 -> R403 33R -> FB402 -> pin 4."""
    return "\n".join([
        "V33 v33 0 %g" % v33,
        "R401 tx v33 10k",
        "Xu401 tx txn v33 0 CMOSINV params: VTH=1.65 TE=2n ROUT=%g" % rol,
        "R406 txn base 470",
        "R407 base 0 10k",
        "Q401 sink base 0 Q2N3904",
        "R402 sink o5 %g" % r402,
        "Xfb401 o5 p5 FB1K",
        "R403 v33 o4 %g" % r403,
        "Xfb402 o4 p4 FB1K",
    ])


def midi_tx_generic(vcc, ra, rc, rout=25):
    """A sender per the MIDI 1.0 drawing: Vcc - RA - pin 4; pin 5 - RC - buffer."""
    return "\n".join([
        "V33 v33 0 3.3",
        "Vsnd vsnd 0 %g" % vcc,
        "Xdrv tx txb vsnd 0 CMOSBUF params: VTH=%g TE=5n ROUT=%g" % (vcc / 2, rout),
        "R_C txb p5 %g" % rc,
        "R_A vsnd p4 %g" % ra,
    ])


def rx_spec(led, rd=220):
    """Receiver per the MIDI 1.0 drawing: pin 4 - 220R - opto LED - pin 5, 1N4148 across the LED."""
    return "\n".join([
        "Rd r4 la %g" % rd,
        "Vif la la2 0",
        "Dled la2 r5 %s" % led,
        "Dprot r5 la D1N4148",
    ])


def rx_ours(led, ifon, ifoff, delay):
    """sheet midi: J402 pin 4 - FB403 - R404 220R - U402 H11L1 LED - FB404 - pin 5, D401 across the LED;
    U402 output open collector, R405 1 k to +3V3 (MIDI_RX = GPIO 1)."""
    return "\n".join([
        "Xfb403 r4 r4f FB1K",
        "R404 r4f la 220",
        "Vif la la2 0",
        "Dled la2 lk %s" % led,
        "D401 lk la D1N4148",
        "Xfb404 lk r5 FB1K",
        "* H11L1: LED current (1 V per mA) -> detector bandwidth (tau 0.2 us, ~1 Mbit/s part)",
        "* -> delay -> Schmitt with IF(on)/IF(off) -> open collector",
        "Hif ifv 0 Vif 1000",
        "Rlp ifv iflp 1k",
        "Clp iflp 0 200p",
        "Elp iflpb 0 iflp 0 1",
        "Tdly iflpb 0 ifd 0 Z0=50 TD=%g" % (delay - 0.14e-6),
        "Rtd ifd 0 50",
        "Su402 rx 0 ifd 0 SH11L1",
        ".model SH11L1 sw vt=%g vh=%g ron=30 roff=1e10" % ((ifon + ifoff) / 2 * 1e3, (ifon - ifoff) / 2 * 1e3),
        "R405 v33 rx 1k",
        "Crx rx 0 15p",
    ])


