def enc_body(ctl_pwl, rpu):
    return "\n".join([
        "V33 v33 0 3.3",
        "Vc ctl 0 PWL(%s)" % ctl_pwl,
        "R601 v33 raw 10k",
        "Sc raw 0 ctl 0 SCONTACT",
        ".model SCONTACT sw vt=0.5 vh=0.1 ron=1 roff=1e12",
        "R602 raw enc 10k",
        "C603 enc 0 10n",
    ] + (["Rpu enc v33 %g" % rpu] if rpu else []))


def pwl_from_events(events, t_end, edge=0.1e-6):
    """events: list of (time, closed 0/1) changes, starting from open."""
    pts = [(0.0, 0)]
    level = 0
    for t, lv in events:
        if lv == level:
            continue
        pts.append((t, level))
        pts.append((t + edge, lv))
        level = lv
    pts.append((t_end, level))
    return " ".join("%.7g %d" % p for p in pts)


