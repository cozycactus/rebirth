# ------------------------------------------------------------------ deck runner

def deck_dir(name):
    sub, base = os.path.split(name)
    return os.path.join(OUT, sub), base


def write_deck(name, body, control):
    """name may carry a subfolder of out/; decks in out/vendor/ use the Microchip model."""
    d, base = deck_dir(name)
    os.makedirs(d, exist_ok=True)
    lib = VENDOR_INCLUDE if os.path.basename(d) == "vendor" else os.path.relpath(os.path.join(HERE, "models.lib"), d)
    text = "\n".join([
        "* %s (generated by sim/run.py)" % base,
        ".include %s" % lib,
        body.strip(),
        ".control",
        "set wr_singlescale",
        "set wr_vecnames",
        control.strip(),
        ".endc",
        ".end",
        "",
    ])
    with open(os.path.join(d, base + ".cir"), "w") as f:
        f.write(text)


def run_deck(name):
    d, base = deck_dir(name)
    r = subprocess.run([NGSPICE, "-b", base + ".cir"], cwd=d, capture_output=True, text=True, timeout=600)
    log = r.stdout + r.stderr
    with open(os.path.join(d, base + ".log"), "w") as f:
        f.write(log)
    bad = [ln for ln in log.splitlines() if ln.lower().startswith(("error", "fatal")) or "singular" in ln.lower()]
    if r.returncode != 0 or bad:
        raise RuntimeError("%s: ngspice rc %d: %s" % (name, r.returncode, "; ".join(bad)[:400]))
    return log


def run_all(decks):
    """decks: list of (name, body, control). Runs them in parallel."""
    for name, body, control in decks:
        write_deck(name, body, control)
    with concurrent.futures.ThreadPoolExecutor(JOBS) as ex:
        list(ex.map(run_deck, [d[0] for d in decks]))


def read_dat(name):
    with open(os.path.join(OUT, name)) as f:
        head = [h.lower() for h in f.readline().split()]
        cols = [[] for _ in head]
        for line in f:
            parts = line.split()
            if len(parts) != len(head):
                continue
            for c, v in zip(cols, parts):
                c.append(float(v))
    return dict(zip(head, cols))


def op_values(log):
    """'name = value' lines printed by `print` in an op run."""
    vals = {}
    for line in log.splitlines():
        if " = " in line:
            k, _, v = line.partition(" = ")
            try:
                vals[k.strip()] = float(v.split()[0])
            except (ValueError, IndexError):
                pass
    return vals


# ------------------------------------------------------------------ waveform helpers

def interp(t, y, t0):
    lo, hi = 0, len(t) - 1
    if t0 <= t[0]:
        return y[0]
    if t0 >= t[-1]:
        return y[-1]
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if t[mid] <= t0:
            lo = mid
        else:
            hi = mid
    f = (t0 - t[lo]) / (t[hi] - t[lo])
    return y[lo] + f * (y[hi] - y[lo])


def crossings(t, y, level, rising=None, t0=None, t1=None):
    out = []
    for i in range(1, len(t)):
        if t0 is not None and t[i] < t0:
            continue
        if t1 is not None and t[i - 1] > t1:
            break
        a, b = y[i - 1] - level, y[i] - level
        if a == b or (a < 0) == (b < 0) and a != 0:
            continue
        up = b > a
        if rising is not None and up != rising:
            continue
        out.append(t[i - 1] + (t[i] - t[i - 1]) * (-a) / (b - a))
    return out


def window(t, y, t0, t1):
    return [v for tt, v in zip(t, y) if t0 <= tt <= t1]


def settle(t, y, final, tol, t0, t1):
    """Time after t0 from which |y - final| stays <= tol until t1 (None: never)."""
    last = None
    for tt, v in zip(t, y):
        if tt < t0 or tt > t1:
            continue
        if abs(v - final) > tol:
            last = tt
    if last is None:
        return 0.0
    if last >= t1 - (t1 - t0) * 0.02:
        return None
    return last - t0


def edge_10_90(t, y, lo, hi, rising, t0, t1):
    a = lo + 0.1 * (hi - lo)
    b = lo + 0.9 * (hi - lo)
    if rising:
        ta, tb = crossings(t, y, a, True, t0, t1), crossings(t, y, b, True, t0, t1)
    else:
        ta, tb = crossings(t, y, b, False, t0, t1), crossings(t, y, a, False, t0, t1)
    if not ta or not tb:
        return None
    return tb[0] - ta[0]


def schmitt(t, y, vtp, vtm, start):
    """Digital output of a Schmitt input; returns list of (time, new_level)."""
    state = start
    out = []
    for tt, v in zip(t, y):
        if state == 0 and v >= vtp:
            state = 1
            out.append((tt, 1))
        elif state == 1 and v <= vtm:
            state = 0
            out.append((tt, 0))
    return out


def wrap180(ph):
    """Phase in degrees to (-180, 180]."""
    w = (ph + 180.0) % 360.0 - 180.0
    return 180.0 if w == -180.0 else w


def us(x):
    return None if x is None else round(x * 1e6, 2)


def mv(x):
    return None if x is None else round(x * 1e3, 3)


# ------------------------------------------------------------------ 1. CV output stage

C51X = 1e-9          # C511-C514 as drawn (gen/build.py)
C51X_BEFORE = 100e-12  # the value before this simulation, kept for comparison
CF_CASES = (C51X, C51X_BEFORE)

# sheet cv_gate, build.py cv_stage(): U503 (MCP6004) unity buffer on VBUS, R51x 1 k
# from the op-amp output to the jack, R52x 10 k from the jack back to the
# inverting input, C51x from the op-amp output to the inverting input, R515-R518
# 100 k pull-down at the + input (the DAC is an ideal source here).
def cv_stage(vbus, vos, ro, fp2, rl, cl, fb_pin="fb", cf=None, vendor=False):
    cf = C51X if cf is None else cf
    if vendor:  # Microchip subckt pins: +in -in V+ V- out
        amp = "Xu503 dac %s vbus 0 amp MCP6001" % fb_pin
    else:
        amp = "Xu503 dac %s amp vbus 0 MCP6004G params: VOS=%g RO=%g FP2=%g" % (fb_pin, vos, ro, fp2)
    lines = [
        "Vbus vbus 0 %g" % vbus,
        "R515 dac 0 100k",
        amp,
        "R511 amp jack 1k",
        "R521 fb jack 10k",
        "C511 fb amp %g" % cf,
        "Rload jack 0 %g" % rl,
    ]
    if cl:
        lines.append("Ccable jack 0 %g" % cl)
    return "\n".join(lines)


def tag(*parts):
    out = []
    for p in parts:
        if isinstance(p, float) or isinstance(p, int):
            out.append(("%g" % p).replace(".", "p").replace("-", "m").replace("+", ""))
        else:
            out.append(str(p))
    return "_".join(out)


# Closed loop: AC response DAC -> jack and steps.
# 10 us: +1 semitone (83.3 mV, 50 ns edge); 310 us: back; 610 us: 1 V -> 0;
# 910 us: 0 -> 2.048 V; 1210 us: 2.048 V -> 0 (MCP4822 slew 0.55 V/us).
SEMI = 1.0 / 12
CV_PWL = " ".join("%.6g %.6g" % p for p in [
    (0, 1.0), (10e-6, 1.0), (10.05e-6, 1 + SEMI), (310e-6, 1 + SEMI), (310.05e-6, 1.0),
    (610e-6, 1.0), (610e-6 + 1.0 / 0.55e6, 0.0), (910e-6, 0.0), (910e-6 + 2.048 / 0.55e6, 2.048),
    (1210e-6, 2.048), (1210e-6 + 2.048 / 0.55e6, 0.0), (1510e-6, 0.0)])


def dc_deck(n, stage):
    return (n, "Vdac dac 0 0\n" + stage, "dc Vdac 0 2.048 0.5m\nwrdata %s.dat v(jack) v(amp)" % os.path.basename(n))


def dc_metrics(n, vos=None):
    """vos None: take the offset from the jack at 1 V (vendor model's own offset)."""
    d = read_dat(n + ".dat")
    x, j = d["v-sweep"], d["v(jack)"]
    off = interp(x, j, 1.0) - 1.0 if vos is None else vos
    first = None  # first DAC code from which the jack follows the DAC within 0.1 mV of the offset
    for xi, ji in zip(x, j):
        if abs(ji - xi - off) <= 0.1e-3:
            first = xi
            break
    return {"offset_mV": mv(off), "err_mV": {"%g" % v: mv(interp(x, j, v) - v) for v in (0.0, 1.0, 2.048)},
            "jack_at_code0_mV": mv(j[0]), "first_tracking_mV": mv(first),
            "amp_at_2048_V": round(interp(x, d["v(amp)"], 2.048), 4)}


def loop_deck(n, stage, cfin):
    """Loop broken at the inverting input (L/C); the op-amp input C is kept on the fb node.
    1 MH / 1 F: open from 1 Hz up against the 10 k feedback node; 1 GH / 1 GF made the
    Microchip model's AC solution ill-conditioned."""
    body = "\n".join(["Vdac dac 0 1.0", stage, "Cfbin fb 0 %s" % cfin, "Lbrk fb fbp 1Meg", "Cinj inj fbp 1",
                      "Vinj inj 0 dc 0 ac 1"])
    ctl = "\n".join(["ac dec 50 1 100Meg", "let T = -v(fb)/v(fbp)", "let tdb = db(T)", "let tph = 180/pi*cph(T)",
                     "wrdata %s.dat tdb tph" % os.path.basename(n)])
    return (n, body, ctl)


def loop_metrics(n):
    d = read_dat(n + ".dat")
    f, g, p = d["frequency"], d["tdb"], d["tph"]
    fc = crossings(f, g, 0.0)
    # phase margin at every |T| = 1 crossing: distance of the phase from -180
    pms = [round(180 - abs(wrap180(interp(f, p, c))), 1) for c in fc]
    # gain margin: -|T| where the phase passes -180 above the last crossover
    gm = None
    pw = [wrap180(v) for v in p]
    for k in range(1, len(f)):
        if abs(pw[k] - pw[k - 1]) > 300 and (not fc or f[k] > fc[-1]):
            gm = round(-g[k], 1)
            break
    return {"fc_kHz": [round(c / 1e3, 1) for c in fc], "pm_deg": pms, "min_pm_deg": min(pms) if pms else None,
            "gm_dB": gm}


def step_deck(n, stage):
    b = os.path.basename(n)
    ctl = "\n".join(["ac dec 50 10 10Meg", "let g = db(v(jack))", "wrdata %s_ac.dat g" % b,
                     "tran 10n 1510u 0 20n", "wrdata %s_tr.dat v(jack) v(amp) v(dac)" % b])
    return (n, "Vdac dac 0 DC 1.0 AC 1 PWL(%s)\n" % CV_PWL + stage, ctl)


def step_metrics(n):
    a = read_dat(n + "_ac.dat")
    f, g = a["frequency"], a["g"]
    g0 = g[0]
    peak = max(g)
    f3 = crossings(f, g, g0 - 3.0, rising=False)
    d = read_dat(n + "_tr.dat")
    t, j = d["time"], d["v(jack)"]
    base = interp(t, j, 9e-6)             # the stage's own offset is not an error here
    top = interp(t, j, 300e-6)
    up = window(t, j, 10e-6, 310e-6)
    fs_final = interp(t, j, 1200e-6)
    fs = window(t, j, 910e-6, 1210e-6)
    return {
        "ac_peak_dB": round(peak - g0, 2), "f_peak_kHz": round(f[g.index(peak)] / 1e3, 1),
        "f3dB_kHz": round(f3[0] / 1e3, 1) if f3 else None,
        "semitone_overshoot_pct": round((max(up) - top) / (top - base) * 100, 1),
        "semitone_settle_1LSB_us": us(settle(t, j, top, 0.5e-3, 10e-6, 310e-6)),
        "fs_overshoot_mV": mv(max(fs) - fs_final),
        "fs_settle_1LSB_us": us(settle(t, j, fs_final, 0.5e-3, 910e-6, 1210e-6)),
        "zero_after_fall_mV": mv(interp(t, j, 1500e-6)),
    }


def short_deck(n, stage):
    body = "\n".join(["Vdac dac 0 2.048", stage, "Vsh shc 0 PWL(0 0 50u 0 50.01u 1 250u 1 250.01u 0)",
                      "Ssh jack 0 shc 0 SSHORT", ".model SSHORT sw vt=0.5 vh=0.1 ron=0.01 roff=1e12"])
    ctl = "\n".join(["tran 10n 400u 0 20n", "let ir = (v(amp)-v(jack))/1k",
                     "wrdata %s.dat v(jack) v(amp) ir" % os.path.basename(n)])
    return (n, body, ctl)


def short_metrics(n):
    d = read_dat(n + ".dat")
    t, j, a, ir = d["time"], d["v(jack)"], d["v(amp)"], d["ir"]
    during = window(t, ir, 100e-6, 249e-6)
    final = interp(t, j, 45e-6)
    return {"i_short_mA": round(max(during) * 1e3, 2), "v_amp_during_V": round(interp(t, a, 200e-6), 3),
            "p_R511_mW": round(max(during) ** 2 * 1e3 * 1e3, 1),
            "jack_peak_after_release_V": round(max(window(t, j, 250e-6, 400e-6)), 3),
            "recover_1LSB_us": us(settle(t, j, final, 0.5e-3, 250e-6, 400e-6))}


BD_CASES = [(vx, rx) for vx in (10.0, -10.0, 12.0, -12.0) for rx in (1e3, 0.01)]


def backdrive_deck(n, stage, vx, rx):
    body = "\n".join(["Vdac dac 0 1.0", stage, "Vext ext 0 %g" % vx, "Rext ext jack %g" % rx])
    ctl = "op\nlet iout = (v(amp)-v(jack))/1k\nlet iin = (v(jack)-v(fb))/10k\nprint v(jack) v(amp) v(fb) iout iin"
    return (n, body, ctl)


def backdrive_metrics(n, vx, rx):
    d, base = deck_dir(n)
    v = op_values(open(os.path.join(d, base + ".log")).read())
    return {"v_ext": vx, "r_ext": rx, "v_jack": round(v["v(jack)"], 3), "v_amp": round(v["v(amp)"], 3),
            "v_fb": round(v["v(fb)"], 3), "i_R511_mA": round(v["iout"] * 1e3, 2),
            "p_R511_mW": round(v["iout"] ** 2 * 1e6, 1), "i_inverting_input_mA": round(v["iin"] * 1e3, 3)}


def bench_cv():
    """CV stage with the generic MCP6004G model (offset, RO and FP2 swept)."""
    res = {"dc": [], "loop": [], "step": [], "short": [], "backdrive": []}
    dc_cases = [(vb, rl, vos) for vb in (5.0, 4.5) for rl in (100e3, 10e3) for vos in (-4.5e-3, 0.0, 4.5e-3)]
    loop_cases = [(cf, rl, cl, ro, 4e6) for cf in CF_CASES for rl in (100e3, 10e3)
                  for cl in (0, 1e-9, 10e-9, 100e-9) for ro in (100, 1000)]
    loop_cases += [(cf, 100e3, cl, 1000, 2e6) for cf in CF_CASES for cl in (0, 10e-9)]
    step_cases = [(cf, 5.0, rl, cl, ro) for cf in CF_CASES for rl in (100e3, 10e3)
                  for cl in (0, 1e-9, 10e-9) for ro in (100, 1000)]
    step_cases += [(C51X, 4.5, 10e3, cl, 1000) for cl in (0, 10e-9)]
    decks = [dc_deck(tag("cv_dc", vb, rl, vos), cv_stage(vb, vos, 100, 4e6, rl, 0)) for vb, rl, vos in dc_cases]
    decks += [loop_deck(tag("cv_loop", cf, rl, cl, ro, fp2), cv_stage(5.0, 0, ro, fp2, rl, cl, fb_pin="fbp", cf=cf),
                        "9p") for cf, rl, cl, ro, fp2 in loop_cases]
    decks += [step_deck(tag("cv_step", cf, vb, rl, cl, ro), cv_stage(vb, 0, ro, 4e6, rl, cl, cf=cf))
              for cf, vb, rl, cl, ro in step_cases]
    decks += [short_deck(tag("cv_short", cl), cv_stage(5.0, 0, 100, 4e6, 100e3, cl)) for cl in (0, 1e-9)]
    decks += [backdrive_deck(tag("cv_back", vx, rx), cv_stage(5.0, 0, 100, 4e6, 1e12, 0), vx, rx)
              for vx, rx in BD_CASES]
    run_all(decks)
    for vb, rl, vos in dc_cases:
        res["dc"].append(dict({"vbus": vb, "rl": rl, "vos_mV": vos * 1e3}, **dc_metrics(tag("cv_dc", vb, rl, vos), vos)))
    for cf, rl, cl, ro, fp2 in loop_cases:
        res["loop"].append(dict({"cf": cf, "rl": rl, "cl": cl, "ro": ro, "fp2": fp2},
                                **loop_metrics(tag("cv_loop", cf, rl, cl, ro, fp2))))
    for cf, vb, rl, cl, ro in step_cases:
        res["step"].append(dict({"cf": cf, "vbus": vb, "rl": rl, "cl": cl, "ro": ro},
                                **step_metrics(tag("cv_step", cf, vb, rl, cl, ro))))
    for cl in (0, 1e-9):
        res["short"].append(dict({"cl": cl}, **short_metrics(tag("cv_short", cl))))
    for vx, rx in BD_CASES:
        res["backdrive"].append(backdrive_metrics(tag("cv_back", vx, rx), vx, rx))
    return res


